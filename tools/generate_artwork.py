TEXTURES_PLAN = [
    ("texture-marble", "Marble", 0.55, 0.10),
    ("texture-travertine", "Travertine", 0.45, 0.14),
    ("texture-ceramic", "Glazed ceramic", 0.30, 0.05),
    ("texture-stone", "Natural stone", 0.40, 0.18),
    ("texture-brushed_metal", "Brushed metal", 0.30, 0.42),
    ("texture-frosted_glass", "Frosted glass", 0.25, 0.06),
    ("texture-basalt", "Basalt", 0.60, 0.16),
    ("texture-sandstone", "Sandstone", 0.50, 0.12),
]


def render_texture(name: str, roughness: float, grain: float) -> Image.Image:
    """Seamless material tile: periodic noise so edges match on all four sides."""
    size = TEXTURE_SIZE
    rng = np.random.default_rng(abs(hash(name)) % (2 ** 31))
    # periodic value noise by tiling a small random field and blurring
    base = rng.random((8, 8))
    field = np.array(Image.fromarray((base * 255).astype(np.uint8)).resize(
        (size, size), Image.BICUBIC), dtype=np.float32) / 255.0
    # make it periodic by blending with a shifted copy
    field = (field + np.roll(field, size // 2, axis=0) * 0.5 + np.roll(field, size // 2, axis=1) * 0.5) / 2.0

    if name.endswith("brushed_metal"):
        bands = np.sin(np.linspace(0, math.tau * 24, size))[None, :] * 0.5 + 0.5
        field = field * 0.35 + bands * 0.65
        colour = np.array(hexc("8D97A3"), dtype=np.float32)
    elif name.endswith("frosted_glass"):
        colour = np.array(hexc("9FC4C9"), dtype=np.float32)
        field = 0.5 + (field - 0.5) * 0.25
    elif name.endswith("ceramic"):
        colour = np.array(hexc("E8E2D6"), dtype=np.float32)
        field = 0.55 + (field - 0.5) * 0.20
    elif name.endswith("basalt"):
        colour = np.array(hexc("3A3D42"), dtype=np.float32)
    elif name.endswith("sandstone"):
        colour = np.array(hexc("C3AC8B"), dtype=np.float32)
    elif name.endswith("travertine"):
        colour = np.array(hexc("CBB79A"), dtype=np.float32)
    elif name.endswith("stone"):
        colour = np.array(hexc("A79C8B"), dtype=np.float32)
    else:
        colour = np.array(hexc("D9D2C6"), dtype=np.float32)

    modulation = 0.72 + field * roughness * 2.0
    arr = np.clip(colour[None, None, :] * modulation[:, :, None], 0, 255)
    if grain > 0:
        arr = arr + rng.normal(0, grain * 12, arr.shape)
    return Image.fromarray(np.clip(arr, 0, 255).astype(np.uint8), "RGB")


