#!/usr/bin/env python3
"""Face It artwork pipeline — curated wallpapers, objects and material textures.

Everything here is original, deterministic, vector-constructed artwork authored
for Face It. There is no photography, no scraped material, no stock library and
no AI-generated imagery with unverifiable provenance, because AGENTS.md §7
requires every bundled asset to be original or rights-verified and to be
reviewed for malformed geometry and accidental text before inclusion.
Procedural construction guarantees that: the geometry is exact by definition and
not one pixel of text exists in any output.

Run from the repository root:

    python3 tools/generate_artwork.py            # full pack + derivatives
    python3 tools/generate_artwork.py --sheet    # also write a review contact sheet
    python3 tools/generate_artwork.py --only thumb  # rebuild derivatives only

Outputs:
    app/src/main/assets/wallpapers/<id>.png           1080 x 2400 master
    app/src/main/assets/wallpapers/thumbs/<id>.png     270 x 600 gallery thumbnail
    app/src/main/assets/objects/<id>.png              1024 x 1024 transparent object
    app/src/main/assets/textures/<id>.png             512 x 512 seamless material tile
    app/src/main/res/drawable-nodpi/faceit_widget_*.png  widget picker previews
    content/artwork/manifest.json                     rights, hashes, dimensions
    content/artwork/index.json                        runtime catalogue for the app

Design rules baked into the renderer
------------------------------------
* Portrait 1080 x 2400 with the focal band kept out of the top 16% (clock,
  status bar) and the bottom 13% (launcher dock), per the asset quality bar.
* Each collection owns a colour graded palette so a pack reads as one body of
  work rather than a random dump.
* Subtle film grain and a light vignette unify matte and gradient surfaces and
  stop large flat areas from banding after colour quantisation.
* No text, no logos, no numerals, no watermarks anywhere.
"""
